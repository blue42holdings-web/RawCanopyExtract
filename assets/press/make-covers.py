# Oct 15: original, blurred "feel of the cover" backgrounds for the press boxes. No logos, no real photos:
# just each magazine's color scheme and cover layout, painted from shapes and blurred.
import random
from PIL import Image, ImageDraw, ImageFilter
W,H=640,800
OUT='/home/claude/rawcanopyextract/assets/press/'
def blob(d,cx,cy,r,col):
    for k in range(10,0,-1):
        rr=r*k/10; a=int(255*(1-k/11)*0.5)
        d.ellipse([cx-rr,cy-rr,cx+rr,cy+rr],fill=col+(a,))

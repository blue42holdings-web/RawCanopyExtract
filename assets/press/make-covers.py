def cover(name,bg,mast,mast_h,photo,bars,frame=None,seed=1,mast_y=40,inset=None):
    # Oct 15 (late, Scott): every cover gets the same masthead band, same height, same place; only lower coverlines vary
    mast=None; mast_h=0; mast_y=0; inset=None; frame=None   # Oct 15 (late): no colored band at the top at all, just the blur
    bars=[b for b in bars if b[1]>=.6]
    random.seed(seed)
    im=Image.new('RGB',(W,H),bg); d=ImageDraw.Draw(im,'RGBA')
    # the cover photo: soft colored masses
    x0,y0,x1,y1=inset or (0,mast_y+mast_h,W,H)
    for (cx,cy,r,col) in photo: blob(d,x0+cx*(x1-x0),y0+cy*(y1-y0),r,col)
    # masthead
    if mast: d.rectangle([40,mast_y,W-40,mast_y+mast_h],fill=mast)
    # headline and coverline bars
    for (x,y,w,h,col) in bars: d.rectangle([x*W,y*H,(x+w)*W,(y+h)*H],fill=col)
    if frame: 
        c,t=frame; d.rectangle([0,0,W-1,H-1],outline=c,width=t)
    im=im.filter(ImageFilter.GaussianBlur(16))
    im.save(OUT+name+'.webp',quality=70)
